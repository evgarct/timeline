// One-off generator for android/.../ui/workout/BodyMapData.kt from the MIT-licensed
// react-native-body-highlighter (https://github.com/HichamELBSI/react-native-body-highlighter):
//
//   gh api repos/HichamELBSI/react-native-body-highlighter/contents/assets/bodyFront.ts -H "Accept: application/vnd.github.raw" > bodyFront.ts
//   (same for bodyBack.ts and LICENSE)
//   node scripts/generate-body-map.mjs <dir with bodyFront.ts bodyBack.ts LICENSE> <commit sha> <output .kt>
//
// The TS files are plain data (an array of { slug, path: { common?, left?, right? } }), so they are
// evaluated after stripping the type annotations. Left/right/common outlines are merged per slug.
import { readFileSync, writeFileSync } from "node:fs";

const [dir, sha, output] = process.argv.slice(2);
if (!dir || !sha || !output) {
  console.error("Usage: node scripts/generate-body-map.mjs <dir> <commit sha> <output.kt>");
  process.exit(1);
}

function load(name) {
  const source = readFileSync(`${dir}/${name}.ts`, "utf8")
    .replace(/^import .*$/gm, "")
    .replace(/export const \w+: BodyPart\[\] =/, "return ");
  return new Function(source)();
}

function shapes(parts) {
  const bySlug = new Map();
  for (const part of parts) {
    const paths = [...(part.path.common ?? []), ...(part.path.left ?? []), ...(part.path.right ?? [])];
    bySlug.set(part.slug, [...(bySlug.get(part.slug) ?? []), ...paths]);
  }
  return [...bySlug.entries()];
}

function kotlinList(entries, indent) {
  return entries.map(([slug, paths]) => (
    `${indent}BodyShape(\n${indent}    "${slug}",\n${indent}    listOf(\n`
    + paths.map((path) => `${indent}        "${path}"`).join(",\n")
    + `\n${indent}    )\n${indent})`
  )).join(",\n");
}

const license = readFileSync(`${dir}/LICENSE`, "utf8").trim().split("\n").map((line) => ` * ${line}`.trimEnd()).join("\n");
const front = shapes(load("bodyFront"));
const back = shapes(load("bodyBack"));

const kotlin = `/*
 * GENERATED by scripts/generate-body-map.mjs — do not edit by hand.
 *
 * Body outline path data derived from react-native-body-highlighter (male body),
 * https://github.com/HichamELBSI/react-native-body-highlighter @ ${sha}
 * Used under its MIT license:
 *
${license}
 */
package com.evgarct.form.ui.workout

internal class BodyShape(val slug: String, val paths: List<String>)

internal object BodyMapData {
    /** Both views share one 724 x 1448 canvas; the back view lives in x = 724..1448. */
    const val VIEW_WIDTH = 724f
    const val VIEW_HEIGHT = 1448f
    const val BACK_OFFSET_X = 724f

    val front: List<BodyShape> = listOf(
${kotlinList(front, "        ")}
    )

    val back: List<BodyShape> = listOf(
${kotlinList(back, "        ")}
    )
}
`;

writeFileSync(output, kotlin);
console.log(`front shapes: ${front.length}, back shapes: ${back.length}, bytes: ${kotlin.length}`);
